data class AndroidExportConfig(
    val appDisplayName: String,
    val packageName: String,
    val versionName: String,
    val versionCode: Int
)

data class GeneratedAndroidProjectFiles(
    val mainActivityKt: String,
    val appBuildGradleKts: String,
    val buildApkScript: String,
    val manifestXml: String,
    val rootBuildGradleKts: String,
    val settingsGradleKts: String,
    val stringsXml: String,
    val readmeMd: String,
    val projectJson: String
)

class ProjectExportEngine(private val context: Context) {

    fun sanitizePackageName(raw: String): String {
        val cleaned = raw.lowercase()
            .replace(Regex("[^a-z0-9._]"), "")
            .split(".")
            .filter { it.isNotBlank() }
            .map { seg -> if (seg.first().isDigit()) "app$seg" else seg }
        return if (cleaned.size >= 2) cleaned.joinToString(".") else "com.promptstudio.generated"
    }

    fun generateFiles(
        project: CloudProject,
        messages: List<CloudMessage>,
        config: AndroidExportConfig
    ): GeneratedAndroidProjectFiles {
        val safePkg = sanitizePackageName(config.packageName)
        val escapedAppName = config.appDisplayName.replace("\"", "\\\"").ifBlank { project.title }
        val escapedSystem = project.systemInstruction
            .replace("\\", "\\\\")
            .replace("\"\"\"", "\\\"\\\"\\\"")
        val escapedSchema = project.jsonSchema
            .replace("\\", "\\\\")
            .replace("\"\"\"", "\\\"\\\"\\\"")

        val mainActivityKt = """
            package $safePkg

            import android.os.Bundle
            import androidx.activity.ComponentActivity
            import androidx.activity.compose.setContent
            import androidx.activity.enableEdgeToEdge
            import androidx.compose.foundation.layout.*
            import androidx.compose.foundation.rememberScrollState
            import androidx.compose.foundation.verticalScroll
            import androidx.compose.material3.*
            import androidx.compose.runtime.*
            import androidx.compose.ui.Modifier
            import androidx.compose.ui.unit.dp
            import com.google.firebase.Firebase
            import com.google.firebase.ai.ai
            import com.google.firebase.ai.type.content
            import com.google.firebase.ai.type.generationConfig
            import kotlinx.coroutines.launch
            import kotlinx.coroutines.withTimeout

            /**
             * Generated by Prompt Studio for Android (Live Firebase AI Logic)
             * Project: ${project.title}
             * Target Gemini Model: ${project.modelId}
             */
            object StudioPromptSpec {
                const val MODEL_ID = "${project.modelId}"
                const val TEMPERATURE = ${project.temperature}f
                const val TOP_P = ${project.topP}f
                const val TOP_K = ${project.topK}
                const val MAX_OUTPUT_TOKENS = ${project.maxOutputTokens}
                const val JSON_MODE = ${project.jsonModeEnabled}
                val SYSTEM_INSTRUCTION = ${"\"\"\""}
$escapedSystem
                ${"\"\"\""}.trimIndent()
                val JSON_SCHEMA = ${"\"\"\""}
$escapedSchema
                ${"\"\"\""}.trimIndent()
            }

            class MainActivity : ComponentActivity() {
                override fun onCreate(savedInstanceState: Bundle?) {
                    super.onCreate(savedInstanceState)
                    enableEdgeToEdge()
                    setContent {
                        MaterialTheme {
                            GeneratedStudioAppScreen()
                        }
                    }
                }
            }

            @OptIn(ExperimentalMaterial3Api::class)
            @Composable
            fun GeneratedStudioAppScreen() {
                var prompt by remember { mutableStateOf("") }
                var output by remember { mutableStateOf("") }
                var loading by remember { mutableStateOf(false) }
                val scope = rememberCoroutineScope()

                val model = remember {
                    Firebase.ai.generativeModel(
                        modelName = StudioPromptSpec.MODEL_ID,
                        generationConfig = generationConfig {
                            temperature = StudioPromptSpec.TEMPERATURE
                            topP = StudioPromptSpec.TOP_P
                            topK = StudioPromptSpec.TOP_K
                            maxOutputTokens = StudioPromptSpec.MAX_OUTPUT_TOKENS
                            if (StudioPromptSpec.JSON_MODE) {
                                responseMimeType = "application/json"
                            }
                        },
                        systemInstruction = StudioPromptSpec.SYSTEM_INSTRUCTION
                            .takeIf { it.isNotBlank() }
                            ?.let { content { text(it) } }
                    )
                }

                Scaffold(
                    topBar = { TopAppBar(title = { Text("$escapedAppName") }) }
                ) { padding ->
                    Column(
                        modifier = Modifier
                            .fillMaxSize()
                            .padding(padding)
                            .padding(16.dp)
                            .verticalScroll(rememberScrollState()),
                        verticalArrangement = Arrangement.spacedBy(12.dp)
                    ) {
                        OutlinedTextField(
                            value = prompt,
                            onValueChange = { prompt = it },
                            label = { Text("پرامپت ورودی") },
                            modifier = Modifier.fillMaxWidth(),
                            minLines = 3
                        )
                        Button(
                            onClick = {
                                scope.launch {
                                    loading = true
                                    output = ""
                                    try {
                                        withTimeout(60_000L) {
                                            model.generateContentStream(prompt).collect { chunk ->
                                                output += chunk.text.orEmpty()
                                            }
                                        }
                                    } catch (e: Exception) {
                                        output = e.localizedMessage ?: "Error"
                                    } finally {
                                        loading = false
                                    }
                                }
                            },
                            enabled = !loading && prompt.isNotBlank(),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Text(if (loading) "در حال اجرا..." else "ارسال به Gemini")
                        }
                        if (output.isNotBlank()) {
                            Card(modifier = Modifier.fillMaxWidth()) {
                                Text(output, modifier = Modifier.padding(16.dp))
                            }
                        }
                    }
                }
            }
        """.trimIndent()

        val appBuildGradleKts = """
            plugins {
                id("com.android.application")
                id("org.jetbrains.kotlin.android")
                id("org.jetbrains.kotlin.plugin.compose")
                id("com.google.gms.google-services")
            }

            android {
                namespace = "$safePkg"
                compileSdk = 35

                defaultConfig {
                    applicationId = "$safePkg"
                    minSdk = 24
