                compileOptions {
                    sourceCompatibility = JavaVersion.VERSION_17
                    targetCompatibility = JavaVersion.VERSION_17
                }
                kotlinOptions { jvmTarget = "17" }
                buildFeatures { compose = true }
            }

            dependencies {
                implementation(platform("androidx.compose:compose-bom:2024.09.00"))
                implementation(platform("com.google.firebase:firebase-bom:35.1.0"))
                implementation("androidx.activity:activity-compose:1.10.1")
                implementation("androidx.compose.material3:material3")
                implementation("androidx.compose.ui:ui")
                implementation("com.google.firebase:firebase-ai")
            }
        """.trimIndent()

        val rootBuildGradleKts = """
            plugins {
                id("com.android.application") version "8.9.1" apply false
                id("org.jetbrains.kotlin.android") version "2.1.0" apply false
                id("org.jetbrains.kotlin.plugin.compose") version "2.1.0" apply false
                id("com.google.gms.google-services") version "4.4.2" apply false
            }
        """.trimIndent()

        val settingsGradleKts = """
            pluginManagement {
                repositories {
                    google()
                    mavenCentral()
                    gradlePluginPortal()
                }
            }
            dependencyResolutionManagement {
                repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
                repositories {
                    google()
                    mavenCentral()
                }
            }
            rootProject.name = "${escapedAppName.replace(" ", "")}"
            include(":app")
        """.trimIndent()

        val manifestXml = """
            <?xml version="1.0" encoding="utf-8"?>
            <manifest xmlns:android="http://schemas.android.com/apk/res/android">
                <uses-permission android:name="android.permission.INTERNET" />
                <application
                    android:allowBackup="true"
                    android:label="@string/app_name"
                    android:supportsRtl="true"
                    android:theme="@android:style/Theme.Material.NoActionBar">
                    <activity
                        android:name=".MainActivity"
                        android:exported="true">
                        <intent-filter>
                            <action android:name="android.intent.action.MAIN" />
                            <category android:name="android.intent.category.LAUNCHER" />
                        </intent-filter>
                    </activity>
                </application>
            </manifest>
        """.trimIndent()

        val stringsXml = """
            <resources>
                <string name="app_name">$escapedAppName</string>
            </resources>
        """.trimIndent()

        val buildApkScript = """
            #!/usr/bin/env bash
            set -euo pipefail
            echo "Building native Android APK for $escapedAppName ($safePkg)..."
            gradle assembleDebug
            echo "APK output path: app/build/outputs/apk/debug/app-debug.apk"
        """.trimIndent()

        val readmeMd = """
            # $escapedAppName ($safePkg)

            Generated natively by **Prompt Studio** for Android with Firebase AI Logic.

            ## Prompt Configuration
            - Model: `${project.modelId}`
            - Temperature: `${project.temperature}`
            - Top-P: `${project.topP}`
            - Top-K: `${project.topK}`
            - Max Output Tokens: `${project.maxOutputTokens}`
            - Structured JSON Mode: `${project.jsonModeEnabled}`

            ## Build APK
            1. Place your `google-services.json` inside `app/`.
            2. Open in Android Studio or run `./build_apk.sh`.
            3. Locate your APK at `app/build/outputs/apk/debug/app-debug.apk`.
        """.trimIndent()

        val projectJson = serializeSingleProject(project, messages).toString(2)

        return GeneratedAndroidProjectFiles(
            mainActivityKt = mainActivityKt,
            appBuildGradleKts = appBuildGradleKts,
            buildApkScript = buildApkScript,
            manifestXml = manifestXml,
            rootBuildGradleKts = rootBuildGradleKts,
            settingsGradleKts = settingsGradleKts,
            stringsXml = stringsXml,
            readmeMd = readmeMd,
            projectJson = projectJson
        )
    }

    suspend fun writeAndroidProjectZip(
        outputStream: OutputStream,
        project: CloudProject,
        messages: List<CloudMessage>,
        config: AndroidExportConfig
    ): Long = withContext(Dispatchers.IO) {
        val safePkg = sanitizePackageName(config.packageName)
        val pkgPath = safePkg.replace(".", "/")
        val files = generateFiles(project, messages, config)

        val entries = linkedMapOf(
            "settings.gradle.kts" to files.settingsGradleKts,
            "build.gradle.kts" to files.rootBuildGradleKts,
            "build_apk.sh" to files.buildApkScript,
            "README.md" to files.readmeMd,
            "project_manifest.json" to files.projectJson,
            "app/build.gradle.kts" to files.appBuildGradleKts,
            "app/src/main/AndroidManifest.xml" to files.manifestXml,
            "app/src/main/res/values/strings.xml" to files.stringsXml,
            "app/src/main/java/$pkgPath/MainActivity.kt" to files.mainActivityKt
        )

        var totalBytes = 0L
        ZipOutputStream(outputStream).use { zip ->
            for ((path, content) in entries) {
                val bytes = content.toByteArray(Charsets.UTF_8)
                zip.putNextEntry(ZipEntry(path))
                zip.write(bytes)
                zip.closeEntry()
                totalBytes += bytes.size
            }
        }
        totalBytes
    }

    suspend fun createShareableProjectZipFile(
        project: CloudProject,
        messages: List<CloudMessage>,
        config: AndroidExportConfig
    ): Pair<File, Long> = withContext(Dispatchers.IO) {
        val dir = File(context.cacheDir, "exports").apply { mkdirs() }
        val safeSlug = config.appDisplayName.lowercase()
            .replace(Regex("[^a-z0-9]+"), "_")
            .trim('_')
            .ifBlank { "prompt_studio_project" }
        val outFile = File(dir, "${safeSlug}_android_apk_project.zip")
        FileOutputStream(outFile).use { fos ->
            writeAndroidProjectZip(fos, project, messages, config)
        }
        outFile to outFile.length()
    }

    suspend fun writeInstalledApkToUri(uri: Uri): Long = withContext(Dispatchers.IO) {
        val sourceApk = File(context.applicationInfo.sourceDir)
        require(sourceApk.exists()) { "فایل APK نصب‌شده در دسترس نیست." }
        var copied = 0L
        context.contentResolver.openOutputStream(uri)?.use { out ->
            FileInputStream(sourceApk).use { input ->
                copied = input.copyTo(out)
            }
        } ?: error("خطا در باز کردن مسیر ذخیره‌سازی فایل.")
        copied
    }

    suspend fun createShareableInstalledApkFile(): Pair<File, Long> = withContext(Dispatchers.IO) {
        val sourceApk = File(context.applicationInfo.sourceDir)
        require(sourceApk.exists()) { "فایل APK نصب‌شده در دسترس نیست." }
        val dir = File(context.cacheDir, "exports").apply { mkdirs() }
        val outFile = File(dir, "PromptStudio_native.apk")
        FileInputStream(sourceApk).use { input ->
            FileOutputStream(outFile).use { output ->
                input.copyTo(output)
            }
        }
        outFile to outFile.length()
    }

    fun exportWorkspaceJson(
        projectsWithMessages: List<Pair<CloudProject, List<CloudMessage>>>
    ): String {
        val root = JSONObject()
        root.put("format", "prompt_studio_cloud_backup_v2")
        root.put("exportedAt", System.currentTimeMillis())
        val projectsArray = JSONArray()
        for ((project, messages) in projectsWithMessages) {
            projectsArray.put(serializeSingleProject(project, messages))
        }
        root.put("projects", projectsArray)
        return root.toString(2)
    }

    fun parseWorkspaceJson(rawJson: String): List<Pair<CloudProject, List<CloudMessage>>> {
        val root = JSONObject(rawJson)
        val projectsArray = root.optJSONArray("projects") ?: return emptyList()
        val result = mutableListOf<Pair<CloudProject, List<CloudMessage>>>()
        for (i in 0 until projectsArray.length()) {
            val obj = projectsArray.getJSONObject(i)
            val project = CloudProject(
                title = obj.optString("title", "پروژه بازیابی‌شده").take(120),
                description = obj.optString("description", "").take(500),
                category = obj.optString("category", "CHAT"),
                modelId = obj.optString("modelId", "gemini-3.8-flash"),
                systemInstruction = obj.optString("systemInstruction", "").take(12000),
                temperature = obj.optDouble("temperature", 0.7).coerceIn(0.0, 2.0),
                topP = obj.optDouble("topP", 0.95).coerceIn(0.05, 1.0),
                topK = obj.optLong("topK", 40L).coerceIn(1L, 100L),
                maxOutputTokens = obj.optLong("maxOutputTokens", 2048L).coerceIn(256L, 8192L),
                jsonModeEnabled = obj.optBoolean("jsonModeEnabled", false),
                jsonSchema = obj.optString("jsonSchema", "").take(12000),
                safetyBalanced = obj.optBoolean("safetyBalanced", true),
                pinned = obj.optBoolean("pinned", false)
            )
            val msgsArr = obj.optJSONArray("messages") ?: JSONArray()
            val msgs = mutableListOf<CloudMessage>()
            for (j in 0 until msgsArr.length()) {
                val m = msgsArr.getJSONObject(j)
                val text = m.optString("content", "").take(60000)
                if (text.isNotBlank()) {
                    msgs.add(
                        CloudMessage(
                            role = if (m.optString("role") == "model") "model" else "user",
                            content = text,
                            modelId = m.optString("modelId", project.modelId).take(64),
                            estimatedTokens = m.optLong("estimatedTokens", 0L).coerceAtLeast(0L),
                            hasImageAttachment = m.optBoolean("hasImageAttachment", false)
                        )
                    )
                }
            }
            result.add(project to msgs)
        }
        return result
    }

    private fun serializeSingleProject(
        project: CloudProject,
        messages: List<CloudMessage>
    ): JSONObject {
        val obj = JSONObject()
        obj.put("title", project.title)
        obj.put("description", project.description)
        obj.put("category", project.category)
        obj.put("modelId", project.modelId)
        obj.put("systemInstruction", project.systemInstruction)
        obj.put("temperature", project.temperature)
        obj.put("topP", project.topP)
        obj.put("topK", project.topK)
        obj.put("maxOutputTokens", project.maxOutputTokens)
        obj.put("jsonModeEnabled", project.jsonModeEnabled)
        obj.put("jsonSchema", project.jsonSchema)
        obj.put("safetyBalanced", project.safetyBalanced)
        obj.put("pinned", project.pinned)
        val msgArray = JSONArray()
        for (m in messages) {
            msgArray.put(
                JSONObject().apply {
                    put("role", m.role)
                    put("content", m.content)
                    put("modelId", m.modelId)
                    put("estimatedTokens", m.estimatedTokens)
                    put("hasImageAttachment", m.hasImageAttachment)
                }
            )
        }
        obj.put("messages", msgArray)
        return obj
    }
}
